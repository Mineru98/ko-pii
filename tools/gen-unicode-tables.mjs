#!/usr/bin/env node
/**
 * 유니코드 테이블 코드젠 — Python unicodedata 를 권위 소스로 사용.
 *
 * Python 원본(unicode_norm.py)의 `_build_digit_fold()` 와 `unicodedata.combining()`
 * 데이터를 그대로 추출해 TS 정적 테이블로 만든다. V8 내장 유니코드 데이터는
 * Python 런타임과 버전이 다를 수 있으므로, 의도적으로 Python 에서 생성한다.
 *
 * 실행: node tools/gen-unicode-tables.mjs            (python3 필요)
 *       node tools/gen-unicode-tables.mjs --check    (커밋분 드리프트 검증, 재생성 아님)
 * 출력: src/ts/src/core/unicode-tables.gen.ts
 *
 * --check 는 gold master 의 동기화 게이트(convert-dicts.py --check 등)와 같은
 * 역할을 한다. 생성 결과가 결정적이므로(버전·타임스탬프 미기입) 커밋분과
 * 바이트 동일해야 하며, 어긋나면 exit 1 로 실패한다. 검증 대상 Python 은
 * 커밋분 테이블과 같은 unicodedata 버전이어야 하므로 CI 에서는 3.12 로 고정.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const check = process.argv.includes("--check");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "src", "ts", "src", "core", "unicode-tables.gen.ts");

const PY = `
import json, sys, unicodedata
fold = []
for cp in range(0x80, 0x20000):
    ch = chr(cp)
    cat = unicodedata.category(ch)
    if cat == "Nd":
        fold.append([cp, str(unicodedata.decimal(ch))])
    elif cat == "No":
        try:
            fold.append([cp, str(unicodedata.digit(ch))])
        except ValueError:
            pass  # 분수 등 단일 자릿값 없는 No 는 제외 (원본과 동일)
comb = []
start = None
for cp in range(0x00, 0x110000):
    if unicodedata.combining(chr(cp)):
        if start is None:
            start = cp
    else:
        if start is not None:
            comb.append([start, cp - 1])
            start = None
if start is not None:
    comb.append([start, 0x10FFFE])
json.dump({"digit_fold": fold, "combining_ranges": comb,
           "unicode_version": unicodedata.unidata_version}, sys.stdout)
`;

const raw = execFileSync("python3", ["-c", PY], {
  encoding: "utf-8",
  maxBuffer: 64 * 1024 * 1024,
});
const { digit_fold: digitFold, combining_ranges: combiningRanges, unicode_version } =
  JSON.parse(raw);

const lines = [];
lines.push("// GENERATED by tools/gen-unicode-tables.mjs — 수동 편집 금지.");
lines.push(`// 데이터 원천: Python unicodedata (Unicode ${unicode_version}) — 원본 _build_digit_fold/combining 과 동일.`);
lines.push("");
lines.push("/** 코드포인트 → ASCII 대체 문자 (Nd=decimal, No=digit). 코드포인트 오름차순. */");
lines.push("export const DIGIT_FOLD: ReadonlyArray<readonly [number, string]> = [");
for (const [cp, ch] of digitFold) {
  lines.push(`  [${cp}, ${JSON.stringify(ch)}],`);
}
lines.push("];");
lines.push("");
lines.push("/** 결합 클래스( combining != 0 ) 코드포인트 구간 [start, end] 포함 범위, 오름차순. */");
lines.push("export const COMBINING_RANGES: ReadonlyArray<readonly [number, number]> = [");
for (const [s, e] of combiningRanges) {
  lines.push(`  [${s}, ${e}],`);
}
lines.push("];");
lines.push("");

const content = lines.join("\n");
if (check) {
  const current = readFileSync(outPath, "utf-8");
  if (current !== content) {
    console.error(
      `drift: src/ts/src/core/unicode-tables.gen.ts 가 현재 Python unicodedata 출력과 다름` +
        ` (커밋분이 다른 Python 버전에서 생성됐거나 재생성을 잊음)` +
        ` — 재생성: node tools/gen-unicode-tables.mjs`,
    );
    process.exit(1);
  }
  console.log("ok: unicode-tables.gen.ts 가 Python unicodedata 와 동기화됨");
  process.exit(0);
}

writeFileSync(outPath, content, "utf-8");
console.log(
  `unicode-tables.gen.ts: DIGIT_FOLD ${digitFold.length} entries, COMBINING_RANGES ${combiningRanges.length} ranges (Unicode ${unicode_version})`,
);
