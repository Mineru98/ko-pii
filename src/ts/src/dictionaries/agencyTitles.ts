/** 주어진 기관에서 유효한 직급·직위 집합 (공통 일반직 + 특정직 + 산하 외청). */
export function validTitlesFor(agency: string): Set<string> {
  const valid = new Set(COMMON_GENERAL_TITLES);
  const direct = SPECIALIZED_TITLES[agency];
  if (direct) for (const t of direct) valid.add(t);
  const children = MINISTRY_TO_AGENCIES[agency];
  if (children) {
    for (const child of children) {
      const titles = SPECIALIZED_TITLES[child];
      if (titles) for (const t of titles) valid.add(t);
    }
  }
  return valid;
}

/** (기관, 직책) 조합이 가능한지 검증. */
export function isValidAgencyTitle(agency: string, title: string): boolean {
  if (!agency || !title) return false;
  return validTitlesFor(agency).has(title);
}

/** 주어진 직책이 유효한 기관 목록 (반대 매핑). */
export function specializedAgenciesFor(title: string): string[] {
  const out: string[] = [];
  for (const [agency, titles] of Object.entries(SPECIALIZED_TITLES)) {
    if (titles.has(title)) out.push(agency);
  }
  return out;
}
