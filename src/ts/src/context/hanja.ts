/** Best-effort 변환. 매핑 없는 한자는 원본 보존.
 *
 *     hanjaToHangul("洪吉童")  // "홍길동"
 *     hanjaToHangul("南宮民秀") // 남궁민수 — 단, 民/秀 는 GIVEN_HANJA 의 "민"/"수"
 */
export function hanjaToHangul(text: string): string {
  if (!text) {
    return text;
  }
  const out: string[] = [];
  let i = 0;
  const n = text.length;
  while (i < n) {
    // 2자 복성 우선 매칭
    if (i + 1 < n) {
      const pair = text.slice(i, i + 2);
      const compound = SURNAME_HANJA.get(pair);
      if (compound !== undefined) {
        out.push(compound);
        i += 2;
        continue;
      }
    }
    const ch = text[i] as string;
    const surname = SURNAME_HANJA.get(ch);
    if (surname !== undefined) {
      out.push(surname);
    } else {
      const given = GIVEN_HANJA.get(ch);
      out.push(given !== undefined ? given : ch);
    }
    i += 1;
  }
  return out.join("");
}

/** 텍스트에 CJK 통합한자 (U+4E00 ~ U+9FFF) 가 포함되어 있는지. */
export function hasHanja(text: string): boolean {
  // 해당 범위는 서러게이트를 포함하지 않으므로 UTF-16 코드 유닛 비교로 충분하다.
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if (code >= 0x4e00 && code <= 0x9fff) {
      return true;
    }
  }
  return false;
}
